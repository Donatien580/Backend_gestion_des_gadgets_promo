-- 1) Une demande peut avoir plusieurs distributions
ALTER TABLE distribution DROP CONSTRAINT IF EXISTS distribution_id_demande_key;

-- 2) Direction bénéficiaire du bordereau global
ALTER TABLE distribution
  ADD COLUMN IF NOT EXISTS structure_beneficiaire VARCHAR(150);

-- 3) Détail par catégorie sur chaque ligne
ALTER TABLE ligne_distribution
  ADD COLUMN IF NOT EXISTS categorie_beneficiaire VARCHAR(30),
  ADD COLUMN IF NOT EXISTS nombre_beneficiaires   INTEGER NOT NULL DEFAULT 1,
  ADD COLUMN IF NOT EXISTS quantite_par_personne  INTEGER;

UPDATE ligne_distribution
   SET quantite_par_personne = quantite_distribuee
 WHERE quantite_par_personne IS NULL;

ALTER TABLE ligne_distribution ALTER COLUMN quantite_par_personne SET NOT NULL;

ALTER TABLE ligne_distribution
  ADD CONSTRAINT chk_ligne_distribution_nombre
      CHECK (nombre_beneficiaires >= 1),
  ADD CONSTRAINT chk_ligne_distribution_total
      CHECK (quantite_distribuee = nombre_beneficiaires * quantite_par_personne);

-- 4) Noms des chefs qui signent le bordereau
CREATE TABLE IF NOT EXISTS signataire_distribution (
    id_signataire          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_distribution        INTEGER      NOT NULL
        REFERENCES distribution (id_distribution) ON DELETE CASCADE,
    categorie_beneficiaire VARCHAR(30),
    nom_complet            VARCHAR(150) NOT NULL,
    ordre                  INTEGER      NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_signataire_distribution
    ON signataire_distribution (id_distribution);